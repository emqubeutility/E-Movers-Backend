-- 3. One survey per service request. Volumes are kept in CFT (shown in the organization's unit).
CREATE TABLE survey (
  survey_id bigint GENERATED BY DEFAULT AS IDENTITY,
  public_id uuid NOT NULL DEFAULT gen_random_uuid(),
  service_request_id bigint NOT NULL,
  surveyed_by_profile_id bigint,
  surveyed_at timestamptz,
  scan_file_id bigint,
  time_to_complete_hours numeric(6, 2),
  storage_days int,
  no_of_days int,
  people_required int,
  people_description varchar(500),
  packing_material_remarks varchar(2000),
  insurance_required boolean NOT NULL DEFAULT false,
  insurance_value numeric(12, 2),
  remarks varchar(2000),
  amount_quoted numeric(12, 2),
  quote_instruction varchar(2000),
  computed_volume_cft numeric(12, 3),
  estimated_volume_cft numeric(12, 3),
  version_no int NOT NULL DEFAULT 0,
  completed_at timestamptz,
  completed_by bigint,
  drop_reason_id int,
  drop_remark varchar(2000),
  dropped_at timestamptz,
  dropped_by bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint,
  deleted_at timestamptz,
  deleted_by bigint,
  row_version int NOT NULL DEFAULT 1,
  CONSTRAINT pk_survey PRIMARY KEY (survey_id),
  CONSTRAINT uq_survey_public_id UNIQUE (public_id),
  CONSTRAINT uq_survey_service_request UNIQUE (service_request_id),
  CONSTRAINT fk_survey_service_request FOREIGN KEY (service_request_id) REFERENCES service_request (service_request_id),
  CONSTRAINT fk_survey_surveyed_by FOREIGN KEY (surveyed_by_profile_id) REFERENCES profile (profile_id),
  CONSTRAINT fk_survey_scan_file FOREIGN KEY (scan_file_id) REFERENCES file_doc (file_doc_id),
  CONSTRAINT fk_survey_drop_reason FOREIGN KEY (drop_reason_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_survey_completed_by FOREIGN KEY (completed_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_survey_dropped_by FOREIGN KEY (dropped_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_survey_created_by FOREIGN KEY (created_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_survey_updated_by FOREIGN KEY (updated_by) REFERENCES app_user (user_id),
  CONSTRAINT ck_survey_numbers CHECK (
    coalesce(time_to_complete_hours, 0) >= 0 AND coalesce(storage_days, 0) >= 0
    AND coalesce(no_of_days, 0) >= 0 AND coalesce(people_required, 0) >= 0
    AND coalesce(insurance_value, 0) >= 0 AND coalesce(amount_quoted, 0) >= 0
  )
);
COMMENT ON TABLE survey IS 'The survey of a service request (one per request).';
COMMENT ON COLUMN survey.surveyed_at IS 'When the survey was actually done.';
COMMENT ON COLUMN survey.scan_file_id IS 'Scanned survey sheet (file_doc).';
COMMENT ON COLUMN survey.computed_volume_cft IS 'Sum of the rooms'' adjusted volumes, in CFT.';
COMMENT ON COLUMN survey.estimated_volume_cft IS 'The surveyor''s own estimate, in CFT.';

CREATE TABLE survey_special_requisite (
  survey_special_requisite_id bigint GENERATED BY DEFAULT AS IDENTITY,
  survey_id bigint NOT NULL,
  requisite_id int NOT NULL,
  remark varchar(500),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  CONSTRAINT pk_survey_special_requisite PRIMARY KEY (survey_special_requisite_id),
  CONSTRAINT uq_survey_special_requisite UNIQUE (survey_id, requisite_id),
  CONSTRAINT fk_survey_special_requisite_survey FOREIGN KEY (survey_id) REFERENCES survey (survey_id) ON DELETE CASCADE,
  CONSTRAINT fk_survey_special_requisite_requisite FOREIGN KEY (requisite_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_survey_special_requisite_created_by FOREIGN KEY (created_by) REFERENCES app_user (user_id)
);
COMMENT ON TABLE survey_special_requisite IS 'Special requisites ticked on a survey (SPECIAL_REQUISITE).';

