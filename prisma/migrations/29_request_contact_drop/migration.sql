-- Enquiry flow: a request starts Assigned, is then Contacted or Dropped (final).

-- 1. Statuses: NEW becomes ASSIGNED; CONTACTED and DROPPED are added; unused ones are removed.
UPDATE parameter_type SET allow_user_values = false WHERE code = 'REQUEST_STATUS';

UPDATE parameter p SET code = 'ASSIGNED', label = 'Assigned', display_order = 1, is_default = true
FROM parameter_type t
WHERE p.parameter_type_id = t.parameter_type_id AND t.code = 'REQUEST_STATUS' AND p.code = 'NEW';

INSERT INTO parameter (parameter_type_id, code, label, display_order, is_default, is_fixed)
SELECT t.parameter_type_id, v.code, v.label, v.n, false, true
FROM parameter_type t
CROSS JOIN (VALUES ('CONTACTED', 'Contacted', 2), ('DROPPED', 'Dropped', 3)) AS v (code, label, n)
WHERE t.code = 'REQUEST_STATUS'
  AND NOT EXISTS (
    SELECT 1 FROM parameter p WHERE p.parameter_type_id = t.parameter_type_id AND p.code = v.code
  );

-- Requests still on a removed status go back to Assigned.
UPDATE service_request sr SET status_id = (
  SELECT p.parameter_id FROM parameter p JOIN parameter_type t USING (parameter_type_id)
  WHERE t.code = 'REQUEST_STATUS' AND p.code = 'ASSIGNED')
WHERE sr.status_id IN (
  SELECT p.parameter_id FROM parameter p JOIN parameter_type t USING (parameter_type_id)
  WHERE t.code = 'REQUEST_STATUS' AND p.code NOT IN ('ASSIGNED', 'CONTACTED', 'DROPPED'));

DELETE FROM parameter p USING parameter_type t
WHERE p.parameter_type_id = t.parameter_type_id AND t.code = 'REQUEST_STATUS'
  AND p.code NOT IN ('ASSIGNED', 'CONTACTED', 'DROPPED');

UPDATE parameter p SET is_fixed = true
FROM parameter_type t
WHERE p.parameter_type_id = t.parameter_type_id AND t.code = 'REQUEST_STATUS';

-- 2. Why an enquiry was dropped (users may add more).
INSERT INTO parameter_type (code, name, description, module_code, is_system, allow_user_values, display_order)
VALUES ('ENQUIRY_DROP_REASON', 'Enquiry Drop Reason', 'Why an enquiry was dropped', 'SALES', true, true, 33)
ON CONFLICT (code) DO NOTHING;

INSERT INTO parameter (parameter_type_id, code, label, display_order)
SELECT t.parameter_type_id, v.code, v.label, v.n
FROM parameter_type t
CROSS JOIN (VALUES
  ('INVALID_ENQUIRY', 'Invalid Enquiry', 1),
  ('NOT_CONTACTABLE', 'Not Able To Contact Customer', 2),
  ('FUTURE', 'Future', 3),
  ('OTHER', 'Other', 4)
) AS v (code, label, n)
WHERE t.code = 'ENQUIRY_DROP_REASON'
  AND NOT EXISTS (
    SELECT 1 FROM parameter p WHERE p.parameter_type_id = t.parameter_type_id AND p.code = v.code
  );

-- 3. Contact and drop details on the request.
ALTER TABLE service_request
  ADD COLUMN contacted_by_profile_id bigint,
  ADD COLUMN contacted_at timestamptz,
  ADD COLUMN drop_reason_id int,
  ADD COLUMN drop_remark varchar(2000),
  ADD COLUMN dropped_at timestamptz,
  ADD COLUMN dropped_by bigint,
  ADD CONSTRAINT fk_service_request_contacted_by FOREIGN KEY (contacted_by_profile_id)
    REFERENCES profile (profile_id),
  ADD CONSTRAINT fk_service_request_drop_reason_id FOREIGN KEY (drop_reason_id)
    REFERENCES parameter (parameter_id),
  ADD CONSTRAINT fk_service_request_dropped_by FOREIGN KEY (dropped_by)
    REFERENCES app_user (user_id);

COMMENT ON COLUMN service_request.contacted_by_profile_id IS 'Who contacted the customer.';
COMMENT ON COLUMN service_request.contacted_at IS 'When the customer was contacted.';
COMMENT ON COLUMN service_request.drop_reason_id IS 'ENQUIRY_DROP_REASON.';
COMMENT ON COLUMN service_request.drop_remark IS 'Why it was dropped, in words.';

-- 4. History of a request: created, updated, contacted, dropped.
CREATE TABLE service_request_log (
  log_id bigint GENERATED BY DEFAULT AS IDENTITY,
  service_request_id bigint NOT NULL,
  action varchar(20) NOT NULL,
  from_status_id int,
  to_status_id int,
  remarks varchar(2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint,
  CONSTRAINT pk_service_request_log PRIMARY KEY (log_id),
  CONSTRAINT ck_service_request_log_action
    CHECK (action IN ('CREATED', 'UPDATED', 'CONTACTED', 'DROPPED')),
  CONSTRAINT fk_service_request_log_request FOREIGN KEY (service_request_id)
    REFERENCES service_request (service_request_id),
  CONSTRAINT fk_service_request_log_from_status FOREIGN KEY (from_status_id)
    REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_log_to_status FOREIGN KEY (to_status_id)
    REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_log_created_by FOREIGN KEY (created_by)
    REFERENCES app_user (user_id)
);
CREATE INDEX ix_service_request_log_request ON service_request_log (service_request_id, created_at DESC);
COMMENT ON TABLE service_request_log IS 'What happened to a service request and who did it.';

-- Existing requests get their "created" entry.
INSERT INTO service_request_log (service_request_id, action, to_status_id, created_at, created_by)
SELECT service_request_id, 'CREATED', status_id, created_at, created_by
FROM service_request
WHERE deleted_at IS NULL;
