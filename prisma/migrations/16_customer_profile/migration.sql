-- Links customers to their people (profiles). INDIVIDUAL = one master profile;
-- COMPANY = one master profile plus any number of contact persons.
BEGIN;

CREATE TABLE customer_profile (
  customer_profile_id bigint GENERATED BY DEFAULT AS IDENTITY,
  customer_id         bigint NOT NULL,
  profile_id          bigint NOT NULL,
  is_master           boolean NOT NULL DEFAULT false,
  created_at          timestamptz NOT NULL DEFAULT now(),
  created_by          bigint,
  updated_at          timestamptz NOT NULL DEFAULT now(),
  updated_by          bigint,
  deleted_at          timestamptz,
  deleted_by          bigint,
  CONSTRAINT pk_customer_profile PRIMARY KEY (customer_profile_id),
  CONSTRAINT uq_customer_profile UNIQUE (customer_id, profile_id),
  CONSTRAINT fk_customer_profile_customer_id FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
  CONSTRAINT fk_customer_profile_profile_id FOREIGN KEY (profile_id) REFERENCES profile (profile_id),
  CONSTRAINT fk_customer_profile_created_by FOREIGN KEY (created_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_customer_profile_updated_by FOREIGN KEY (updated_by) REFERENCES app_user (user_id),
  CONSTRAINT fk_customer_profile_deleted_by FOREIGN KEY (deleted_by) REFERENCES app_user (user_id)
);
CREATE INDEX ix_customer_profile_profile_id ON customer_profile (profile_id);
CREATE UNIQUE INDEX uq_customer_profile_master ON customer_profile (customer_id)
  WHERE is_master AND deleted_at IS NULL;

COMMENT ON TABLE customer_profile IS 'People of a customer: an individual''s own profile, or a company''s contact persons.';
COMMENT ON COLUMN customer_profile.is_master IS 'Yes = the main person of the customer. One per customer.';

-- Move the existing links off profile.
INSERT INTO customer_profile (customer_id, profile_id, is_master, created_at, created_by)
SELECT customer_id, profile_id, is_master_profile, created_at, created_by
FROM profile
WHERE customer_id IS NOT NULL;

ALTER TABLE profile DROP CONSTRAINT ck_profile_master_needs_owner;
ALTER TABLE profile DROP CONSTRAINT ck_profile_one_owner;
DROP INDEX IF EXISTS uq_profile_master_per_customer;
DROP INDEX IF EXISTS uq_profile_master_per_company;
DROP INDEX IF EXISTS ix_profile_customer_id;
ALTER TABLE profile DROP CONSTRAINT fk_profile_customer_id;
ALTER TABLE profile DROP COLUMN customer_id;
ALTER TABLE profile DROP COLUMN is_master_profile;

COMMIT;
