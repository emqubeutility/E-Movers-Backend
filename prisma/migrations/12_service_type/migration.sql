-- Service types: the services offered under each service group (a SERVICE_GROUP parameter).
BEGIN;

CREATE TABLE service_type (
  service_type_id  integer GENERATED BY DEFAULT AS IDENTITY,
  service_group_id integer NOT NULL,
  name             varchar(250) NOT NULL,
  display_order    smallint NOT NULL DEFAULT 0,
  is_active        boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  created_by       bigint,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       bigint,
  CONSTRAINT pk_service_type PRIMARY KEY (service_type_id),
  CONSTRAINT fk_service_type_group FOREIGN KEY (service_group_id) REFERENCES parameter (parameter_id),
  CONSTRAINT uq_service_type_name UNIQUE (service_group_id, name)
);

CREATE INDEX ix_service_type_group ON service_type (service_group_id);

COMMENT ON TABLE service_type IS 'Services offered under a service group.';
COMMENT ON COLUMN service_type.service_group_id IS 'parameter of type SERVICE_GROUP';

COMMIT;
