-- Files kept on our server, service groups as their own table (with an image), and service requests.
BEGIN;

-- 1. Files stored on the server: the name shown to users and where the file is kept.
CREATE TABLE file_doc (
  file_doc_id  bigint GENERATED BY DEFAULT AS IDENTITY,
  name         varchar(255) NOT NULL,
  path         varchar(500) NOT NULL,
  mime_type    varchar(100),
  size_bytes   bigint,
  created_at   timestamptz NOT NULL DEFAULT now(),
  created_by   bigint,
  updated_at   timestamptz NOT NULL DEFAULT now(),
  updated_by   bigint,
  deleted_at   timestamptz,
  deleted_by   bigint,
  CONSTRAINT pk_file_doc PRIMARY KEY (file_doc_id),
  CONSTRAINT uq_file_doc_path UNIQUE (path)
);
COMMENT ON TABLE file_doc IS 'A file stored on our server.';
COMMENT ON COLUMN file_doc.path IS 'Location of the file on the server, relative to the upload folder.';

-- 2. Service groups move from the SERVICE_GROUP parameter to their own table.
CREATE TABLE service_group (
  service_group_id integer GENERATED BY DEFAULT AS IDENTITY,
  code             varchar(60) NOT NULL,
  name             varchar(150) NOT NULL,
  file_id          bigint,
  display_order    smallint NOT NULL DEFAULT 0,
  is_active        boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  created_by       bigint,
  updated_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       bigint,
  CONSTRAINT pk_service_group PRIMARY KEY (service_group_id),
  CONSTRAINT uq_service_group_code UNIQUE (code),
  CONSTRAINT uq_service_group_name UNIQUE (name),
  CONSTRAINT fk_service_group_file_id FOREIGN KEY (file_id) REFERENCES file_doc (file_doc_id)
);
COMMENT ON TABLE service_group IS 'Home, office, international relocation and so on; file_id is its image.';

INSERT INTO service_group (code, name, display_order, is_active)
SELECT p.code, p.label, p.display_order, p.is_active
FROM parameter p JOIN parameter_type t ON t.parameter_type_id = p.parameter_type_id
WHERE t.code = 'SERVICE_GROUP';

-- 3. Service types point at the new table.
ALTER TABLE service_type DROP CONSTRAINT fk_service_type_group;

UPDATE service_type st
SET service_group_id = sg.service_group_id
FROM parameter p JOIN service_group sg ON sg.code = p.code
WHERE p.parameter_id = st.service_group_id;

ALTER TABLE service_type
  ADD CONSTRAINT fk_service_type_group FOREIGN KEY (service_group_id) REFERENCES service_group (service_group_id);
COMMENT ON COLUMN service_type.service_group_id IS 'The service group this service belongs to.';

-- 4. The parameter type is no longer used.
DELETE FROM parameter
WHERE parameter_type_id = (SELECT parameter_type_id FROM parameter_type WHERE code = 'SERVICE_GROUP');
DELETE FROM parameter_type WHERE code = 'SERVICE_GROUP';

-- 5. Service requests: one row per enquiry; group-specific fields stay NULL when they do not apply.

CREATE TABLE service_request (
  service_request_id            bigint GENERATED BY DEFAULT AS IDENTITY,
  public_id                     uuid NOT NULL DEFAULT gen_random_uuid(),
  request_no                    varchar(20),
  organization_id               bigint NOT NULL,
  customer_id                   bigint NOT NULL,
  executive_profile_id          bigint,
  service_group_id              integer NOT NULL,
  service_type_id               integer NOT NULL,
  international_service_type_id integer,
  title                         varchar(250) NOT NULL,
  residence_type_id             integer,
  move_date                     date,
  volume_cbm                    numeric(10,2),
  from_address_id               bigint,
  to_address_id                 bigint,
  enquiry_channel_id            integer,
  referral_id                   integer,
  survey_required               boolean NOT NULL DEFAULT false,
  survey_type_id                integer,
  survey_date                   date,
  survey_time                   time,
  storage_start_date            date,
  storage_end_date              date,
  pick_and_pack                 boolean NOT NULL DEFAULT false,
  remarks                       text,
  status_id                     integer NOT NULL,
  created_at                    timestamptz NOT NULL DEFAULT now(),
  created_by                    bigint,
  updated_at                    timestamptz NOT NULL DEFAULT now(),
  updated_by                    bigint,
  deleted_at                    timestamptz,
  deleted_by                    bigint,
  row_version                   integer NOT NULL DEFAULT 1,
  CONSTRAINT pk_service_request PRIMARY KEY (service_request_id),
  CONSTRAINT uq_service_request_public_id UNIQUE (public_id),
  CONSTRAINT uq_service_request_request_no UNIQUE (request_no),
  CONSTRAINT fk_service_request_organization_id FOREIGN KEY (organization_id) REFERENCES organization (organization_id),
  CONSTRAINT fk_service_request_customer_id FOREIGN KEY (customer_id) REFERENCES customer (customer_id),
  CONSTRAINT fk_service_request_executive FOREIGN KEY (executive_profile_id) REFERENCES employee (profile_id),
  CONSTRAINT fk_service_request_service_group_id FOREIGN KEY (service_group_id) REFERENCES service_group (service_group_id),
  CONSTRAINT fk_service_request_service_type_id FOREIGN KEY (service_type_id) REFERENCES service_type (service_type_id),
  CONSTRAINT fk_service_request_intl_service_type_id FOREIGN KEY (international_service_type_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_residence_type_id FOREIGN KEY (residence_type_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_from_address_id FOREIGN KEY (from_address_id) REFERENCES address (address_id),
  CONSTRAINT fk_service_request_to_address_id FOREIGN KEY (to_address_id) REFERENCES address (address_id),
  CONSTRAINT fk_service_request_enquiry_channel_id FOREIGN KEY (enquiry_channel_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_referral_id FOREIGN KEY (referral_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_survey_type_id FOREIGN KEY (survey_type_id) REFERENCES parameter (parameter_id),
  CONSTRAINT fk_service_request_status_id FOREIGN KEY (status_id) REFERENCES parameter (parameter_id),
  CONSTRAINT ck_service_request_storage_dates CHECK (storage_end_date IS NULL OR storage_start_date IS NULL OR storage_end_date >= storage_start_date)
);

CREATE INDEX ix_service_request_organization ON service_request (organization_id) WHERE deleted_at IS NULL;
CREATE INDEX ix_service_request_customer ON service_request (customer_id);
CREATE INDEX ix_service_request_group ON service_request (service_group_id);
CREATE INDEX ix_service_request_status ON service_request (status_id);

COMMENT ON TABLE service_request IS 'A customer enquiry for one service group; addresses live in the address table.';

COMMIT;
